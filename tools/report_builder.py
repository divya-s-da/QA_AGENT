"""DOCX report builder tool for interactive (ADK web) navigator runs.

The pipeline renders its own reports; this tool exists so a navigator driven
interactively in ADK web can hand back a Word document with verdict tables and
the screenshots it captured, just by calling one tool at the end of its run.
"""

import json
import os

from google.adk.tools.tool_context import ToolContext

from .docx_report import generate_docx_report
from .screenshot_tool import evidence_dir


def build_docx_report(
    tool_context: ToolContext,
    site_url: str = "",
    report_text: str = "",
) -> str:
    """Build a DOCX report from the evidence recorded in this session's state.

    Reads tool_context.state['test_evidence'] (list of check records with
    check_id/status/note/screenshot_path), embeds every screenshot captured in this session with a
    verdict caption, and saves qa_report_<timestamp>.docx. Returns the path.
    """
    evidence = tool_context.state.get("test_evidence") or []
    if not isinstance(evidence, list):
        evidence = []
    verdicts = []
    for item in evidence:
        if not isinstance(item, dict):
            continue
        verdicts.append({
            "check_id": item.get("check_id", "?"),
            "verdict": item.get("status", "BLOCKED"),
            "reason": item.get("note", ""),
            "screen_id": item.get("screen_id", "session"),
            "screenshot_path": item.get("screenshot_path", ""),
        })
    failed = any(v["verdict"] == "FAIL" for v in verdicts)
    blocked = any(v["verdict"] == "BLOCKED" for v in verdicts)
    passed = any(v["verdict"] == "PASS" for v in verdicts)
    if failed:
        overall = "FAIL"
    elif blocked and passed:
        overall = "PASS_WITH_CAVEATS"
    elif blocked or not verdicts:
        overall = "BLOCKED"
    else:
        overall = "PASS"
    screen_results = [{
        "screen_id": "session",
        "route": site_url or "",
        "overall": overall,
        "verdicts": verdicts,
    }]
    if not report_text:
        report_text = "Interactive QA session report (generated by navigator)."
    output_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = generate_docx_report(
        report_text=report_text,
        all_screen_results_json=json.dumps(screen_results, default=str),
        site_url=site_url,
        screenshots_dir=evidence_dir(),
        output_dir=output_dir,
    )
    return f"DOCX report saved: {path}"
